export function renderTemplatePreview(
  templateHtml: string,
  stylesCss: string,
  data: ResumeData
): string {
  const template = Handlebars.compile(templateHtml);
  return template(data).replace(
    /<!--\s*INLINE_STYLES\s*-->/,
    () => `<style>${stylesCss}</style>`
  );
}
